      const listMatch = etfs.find((e) => e.code === cleanCode);
      const initialLive = cached || listMatch;

      // 先用本地已有实时数据立即渲染，避免交互延迟
      applyEtfDataToForm(cleanCode, fallbackName, dbTemplate, initialLive, mode);

